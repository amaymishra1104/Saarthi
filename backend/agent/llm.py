import os
import re
import json
from typing import Dict, Any, Optional, List
from pydantic import BaseModel, Field
from backend.config import settings
from .guards import OutputGuard

class LLMProposal(BaseModel):
    intent: str  # PAYMENT_COMPLAINT, GENERAL_FAQ, STATUS_INQUIRY
    language: str = "en"  # en, hi, hinglish
    is_faq: bool = False
    faq_response: Optional[str] = None
    extracted_txn_id: Optional[str] = None
    extracted_amount: Optional[float] = None
    extracted_merchant: Optional[str] = None
    proposed_tool: Optional[str] = None
    proposed_arguments: Dict[str, Any] = Field(default_factory=dict)
    reasoning: str = ""
    suggested_message: Optional[str] = None

class LLMWrapper:
    """
    Provider-agnostic LLM interface with deterministic MOCK_LLM fallback.
    The LLM proposes actions, but application code decides what actually runs.
    """
    def __init__(self):
        self.provider = settings.LLM_PROVIDER
        self.model = settings.LLM_MODEL
        # Real LLM requires MOCK_LLM=false AND a usable key.
        self.emergent_key = settings.EMERGENT_LLM_KEY
        self.gemini_key = settings.GEMINI_API_KEY
        has_key = bool(self.emergent_key) or bool(self.gemini_key)
        self.mock_mode = settings.MOCK_LLM or not has_key
        self._gemini_client = None

        if not self.mock_mode and self.gemini_key and not self.emergent_key:
            # Legacy direct-Gemini path (only when no universal key present)
            try:
                import google.generativeai as genai
                genai.configure(api_key=self.gemini_key)
                self._gemini_client = genai.GenerativeModel(self.model)
            except Exception:
                self.mock_mode = True

    def detect_language(self, text: str) -> str:
        """Detects whether user prompt is English, Hindi (Devanagari), or Hinglish."""
        # Devanagari Unicode range
        if re.search(r'[\u0900-\u097F]', text):
            return "hi"
        hinglish_words = {"mera", "meri", "cut", "gaya", "gaye", "paise", "paisa", "rupaye", "rupay", "par", "nahi", "aaya", "hua", "batao", "karo", "wapas", "kyun", "kya", "hota", "hai"}
        words = set(re.findall(r'\b[a-zA-Z]+\b', text.lower()))
        if len(words.intersection(hinglish_words)) >= 2:
            return "hinglish"
        return "en"

    async def analyze_complaint(self, text: str, customer_id: str) -> LLMProposal:
        """
        UNDERSTAND stage: Analyzes customer complaint, detects language,
        extracts transaction indicators, and proposes initial investigation tool.
        """
        # Rule 4: Sanitize context before processing
        safe_text = OutputGuard.sanitize_context_for_llm(text)
        lang = self.detect_language(safe_text)

        if not self.mock_mode and self.emergent_key:
            try:
                return await self._call_emergent_understand(safe_text, customer_id, lang)
            except Exception:
                # Graceful fallback to deterministic mock engine on API hiccup
                pass
        elif not self.mock_mode and self._gemini_client:
            try:
                return await self._call_gemini_understand(safe_text, customer_id, lang)
            except Exception:
                pass

        return self._mock_understand(safe_text, customer_id, lang)

    def _mock_understand(self, text: str, customer_id: str, lang: str) -> LLMProposal:
        lower = text.lower()

        # 1. Check for General FAQ (Scenario I: "what does a debit mean?")
        faq_patterns = [
            ("what does a debit mean", "A debit means funds have been deducted from your bank account by your issuing bank. In failed payments, debited funds are either settled or automatically reversed back by the clearing network."),
            ("what is a debit freeze", "A debit freeze is a temporary security hold placed by a bank that prevents outgoing transactions while allowing incoming deposits."),
            ("how long does a refund take", "Standard UPI refunds take 24 to 48 hours; card refunds take 3 to 5 business days per banking clearing standards."),
            ("what is upi utr", "A UTR (Unique Transaction Reference) is a 12-digit number generated by the banking switch to track UPI payments across banks."),
            ("kya hota hai debit", "Debit ka matlab hota hai ki aapke bank account se paise kat chuke hain. Agar transaction fail ho gaya hai, to banking rules ke tahat paise auto-reverse ho jate hain."),
        ]
        for query, ans in faq_patterns:
            if query in lower:
                resp = ans
                if lang == "hi" or lang == "hinglish":
                    resp = "Debit ka matlab hota hai ki aapke bank account se paise kat chuke hain. Agar merchant ko credit nahi mila, to banking network dwara auto-reversal initiate kiya jata hai."
                return LLMProposal(
                    intent="GENERAL_FAQ",
                    language=lang,
                    is_faq=True,
                    faq_response=resp,
                    reasoning="Query identified as general informational FAQ. No financial case creation required."
                )

        # 2. Extract Txn ID if explicitly provided (e.g., TXN-1001)
        txn_match = re.search(r'\b(TXN-\d{4}[A-Z]?)\b', text, re.IGNORECASE)
        txn_id = txn_match.group(1).upper() if txn_match else None

        # 3. Extract Amount (e.g. ₹2,000, 2000, Rs 1500)
        amt_match = re.search(r'(?:₹|rs\.?|inr)?\s*([0-9]{1,3}(?:,[0-9]{3})*(?:\.[0-9]{2})?|[0-9]+)\s*(?:rs|rupees|rupaye)?', text, re.IGNORECASE)
        amount = None
        if amt_match:
            try:
                raw_amt = amt_match.group(1).replace(",", "")
                val = float(raw_amt)
                # Ensure plausible transaction amount
                if val >= 10:
                    amount = val
            except ValueError:
                pass

        # 4. Extract Merchant
        merchants = ["zomato", "swiggy", "amazon", "cryptopay", "croma", "uber", "flipkart", "blinkit", "myntra", "ola"]
        found_merchant = None
        for m in merchants:
            if m in lower:
                found_merchant = m.title()
                break

        # Map known demo scenario text hints if txn_id wasn't explicit
        if not txn_id:
            if "duplicate" in lower or "twice" in lower or "do baar" in lower:
                txn_id = "TXN-1003B"
            elif "cryptopay" in lower or "crypto" in lower:
                txn_id = "TXN-1004"
            elif "12000" in lower or "12,000" in lower or "croma" in lower:
                txn_id = "TXN-1005"
            elif "uber" in lower or "1800" in lower:
                txn_id = "TXN-1006"
            elif "flipkart" in lower:
                txn_id = "TXN-1007"
            elif "blinkit" in lower or "1500" in lower or "mera 1500 cut gaya" in lower:
                txn_id = "TXN-1008"
            elif "swiggy" in lower:
                txn_id = "TXN-1002"
            elif "zomato" in lower or "2000" in lower or "2,000" in lower:
                txn_id = "TXN-1001"

        return LLMProposal(
            intent="PAYMENT_COMPLAINT",
            language=lang,
            is_faq=False,
            extracted_txn_id=txn_id,
            extracted_amount=amount,
            extracted_merchant=found_merchant,
            proposed_tool="lookup_transaction",
            proposed_arguments={"txn_id": txn_id, "customer_id": customer_id, "amount": amount},
            reasoning=f"Identified payment complaint in language '{lang}'. Proposing lookup_transaction to inspect core transaction state."
        )

    async def _call_emergent_understand(self, text: str, customer_id: str, lang: str) -> LLMProposal:
        """Real LLM path via the Emergent universal key (any provider/model)."""
        from emergentintegrations.llm.chat import LlmChat, UserMessage, TextDelta, StreamDone

        system_prompt = (
            "You are the intelligence component of SAARTHI, an autonomous payment dispute resolver. "
            "Analyze the customer's complaint and reply STRICTLY as a single JSON object (no markdown) with fields: "
            "intent (PAYMENT_COMPLAINT or GENERAL_FAQ), language (en, hi, hinglish), is_faq (bool), "
            "faq_response (str or null), extracted_txn_id (str like 'TXN-1001' or null), extracted_amount (float or null), "
            "extracted_merchant (str or null), reasoning (short str)."
        )
        chat = LlmChat(
            api_key=self.emergent_key,
            session_id=f"saarthi-{customer_id}",
            system_message=system_prompt,
        ).with_model(self.provider, self.model)

        raw = ""
        async for ev in chat.stream_message(UserMessage(text=text)):
            if isinstance(ev, TextDelta):
                raw += ev.content
            elif isinstance(ev, StreamDone):
                break

        clean_json = re.search(r'\{[\s\S]*\}', raw)
        if clean_json:
            data = json.loads(clean_json.group(0))
            return LLMProposal(
                intent=data.get("intent", "PAYMENT_COMPLAINT"),
                language=data.get("language", lang),
                is_faq=data.get("is_faq", False),
                faq_response=data.get("faq_response"),
                extracted_txn_id=data.get("extracted_txn_id"),
                extracted_amount=data.get("extracted_amount"),
                extracted_merchant=data.get("extracted_merchant"),
                proposed_tool="lookup_transaction",
                proposed_arguments={"txn_id": data.get("extracted_txn_id"), "customer_id": customer_id},
                reasoning=data.get("reasoning", f"Parsed via {self.provider}/{self.model}.")
            )
        # Unparseable output -> fall back to deterministic parser
        return self._mock_understand(text, customer_id, lang)

    def _call_gemini_understand(self, text: str, customer_id: str, lang: str) -> LLMProposal:
        # Prompt structured instructions to Gemini
        system_prompt = (
            "You are the intelligence component of SAARTHI, an autonomous payment dispute resolver. "
            "Analyze the customer's input and reply strictly in valid JSON with fields: "
            "intent (PAYMENT_COMPLAINT or GENERAL_FAQ), language (en, hi, hinglish), is_faq (bool), "
            "faq_response (str or null), extracted_txn_id (str or null), extracted_amount (float or null), "
            "extracted_merchant (str or null), proposed_tool (must be 'lookup_transaction' or null), "
            "reasoning (str)."
        )
        response = self._gemini_client.generate_content(f"{system_prompt}\nCustomer: {text}")
        clean_json = re.search(r'\{[\s\S]*\}', response.text)
        if clean_json:
            data = json.loads(clean_json.group(0))
            return LLMProposal(
                intent=data.get("intent", "PAYMENT_COMPLAINT"),
                language=data.get("language", lang),
                is_faq=data.get("is_faq", False),
                faq_response=data.get("faq_response"),
                extracted_txn_id=data.get("extracted_txn_id"),
                extracted_amount=data.get("extracted_amount"),
                extracted_merchant=data.get("extracted_merchant"),
                proposed_tool=data.get("proposed_tool", "lookup_transaction"),
                proposed_arguments={"txn_id": data.get("extracted_txn_id"), "customer_id": customer_id},
                reasoning=data.get("reasoning", "Parsed via Gemini model.")
            )
        return self._mock_understand(text, customer_id, lang)

    def format_customer_message(
        self,
        case_id: str,
        template_type: str,
        lang: str,
        context: Dict[str, Any]
    ) -> str:
        """
        Formats customer-facing updates ensuring multi-language fidelity
        and zero credential requests (enforced via OutputGuard).
        """
        amount = context.get("amount", "")
        merchant = context.get("merchant", "the merchant")
        rrn = context.get("rrn", "UTR-99210488")
        tat = context.get("tat", "24-48 business hours")

        if template_type == "RESOLVED_VERIFIED":
            if lang == "hi" or lang == "hinglish":
                msg = (
                    f"Aapka ₹{amount} ka payment jo {merchant} par fail hua tha, verify ho gaya hai. "
                    f"Humne aapka reversal safaltapoorvak process kar diya hai (Bank Ref: {rrn}). "
                    f"Paise aapke account me agle {tat} me credit ho jayenge."
                )
            else:
                msg = (
                    f"We verified that your payment of ₹{amount} to {merchant} failed while your account was debited. "
                    f"Your reversal has been successfully processed and verified (Bank Ref: {rrn}). "
                    f"Funds will reflect in your source account within {tat}."
                )

        elif template_type == "UNCONFIRMED_PENDING":
            if lang == "hi" or lang == "hinglish":
                msg = (
                    f"Humne aapke ₹{amount} ke transaction ki jaanch ki hai. Banking clearing network par ye abhi "
                    f"processing me hai, isliye main ise abhi failed ya successful nahi keh sakta. "
                    f"Humne aapka case #{case_id} open kar diya hai. Jaise hi bank settlement status aayega, "
                    f"hum aapko turant update bhejenge."
                )
            else:
                msg = (
                    f"We checked your transaction of ₹{amount} to {merchant}. It is currently in banking clearing. "
                    f"I can't call it failed or successful yet. We have opened tracked case #{case_id} and will "
                    f"automatically notify you as soon as the definitive settlement status is confirmed by the bank."
                )

        elif template_type == "REQUIRE_APPROVAL":
            if lang == "hi" or lang == "hinglish":
                msg = (
                    f"Aapka ₹{amount} ka payment fail hua hai. Kyunki ye amount hamari auto-reversal limit se adhik hai, "
                    f"humne ise supervisor approval queue me bhej diya hai (Case #{case_id}). "
                    f"Senior officer ke approve karte hi reversal execute kar diya jayega."
                )
            else:
                msg = (
                    f"Your transaction of ₹{amount} with {merchant} has been verified as failed. "
                    f"Since the amount exceeds the autonomous execution threshold, your case #{case_id} has been "
                    f"routed to a senior operations supervisor for priority sign-off."
                )

        elif template_type == "ESCALATED_RISK":
            if lang == "hi" or lang == "hinglish":
                msg = (
                    f"Aapke case #{case_id} ko hamari Payments Security team ko transfer kar diya gaya hai. "
                    f"Ek specialist agent iski jaanch karke aapse sampark karega."
                )
            else:
                msg = (
                    f"Your case #{case_id} has been escalated to our Payments Security & Operations team for manual review. "
                    f"A human agent will review the switch telemetry and update you shortly."
                )

        elif template_type == "VERIFICATION_FAILED":
            if lang == "hi" or lang == "hinglish":
                msg = (
                    f"Humne reversal initiate kiya tha, lekin banking state re-check me settlement mismatch paya gaya. "
                    f"Suraksha ke liye case #{case_id} ko human team ko escalate kar diya gaya hai. Reversal dobara nahi chalaya jayega."
                )
            else:
                msg = (
                    f"A reversal order was transmitted, but our post-action verification check did not confirm settlement. "
                    f"In accordance with policy, we have halted automation and escalated Case #{case_id} to an operations agent."
                )

        elif template_type == "IDEMPOTENCY_BLOCKED":
            if lang == "hi" or lang == "hinglish":
                msg = (
                    f"Aapke is transaction ke liye reversal pehle hi process kiya ja chuka hai. "
                    f"Double debit se bachane ke liye duplicate request ko block kar diya gaya hai. Reference: {rrn}."
                )
            else:
                msg = (
                    f"A reversal for this transaction has already been initiated previously. "
                    f"To prevent duplicate debit or double refund, repeated processing is blocked. Reference: {rrn}."
                )

        else:
            msg = f"Case #{case_id} update: Our team is investigating your dispute with {merchant}."

        # Pass through the non-negotiable Output Guard
        is_safe, final_text = OutputGuard.sanitize_and_validate(msg)
        return final_text

llm_wrapper = LLMWrapper()

